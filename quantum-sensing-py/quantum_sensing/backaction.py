# Backaction channel
# ---------------------------------------------------------------------------

def get_state_backaction(
    *,
    s=0.0,
    chi_ba=0.0,
    ba_type="shear",
    theta_sig=0.0,
    theta_ba=0.0,
    chain=("ba", "sig"),
    eta_in=1.0,
    eta_out=1.0,
    pn=0.0,
    state="coherent",
    nbar=4.0,
    squeeze_angle=0.0,
    sqz_fraction=0.5,
    parity=+1,
    N_basis=40,
    rho=None,
):
    """
    Apply an ordered chain of signal / backaction / noise stages to an input
    state and return the output (ket for unitary-only chains, else dm).

    Parameters
    ----------
    s        : displacement signal amplitude (the estimated parameter;
               use param_type="s" with calculate_qfi / calculate_sld)
    chi_ba   : backaction strength (shear chi or Kerr phase per photon^2)
    ba_type  : "shear" (linearized ponderomotive) or "kerr" (n^2)
    chain    : ordered stage names from
               ("sig", "ba", "basig", "loss_in", "loss_out", "pn");
               "basig" applies exp(-i (s X_sig + G_ba)) in one unitary (BA3)
    eta_in, eta_out : transmissions of the loss_in / loss_out stages
    pn       : phase-noise rms (rad) of the pn stage
    state, nbar, squeeze_angle, sqz_fraction, parity :
               input-state family and options (see make_state); ignored when
               rho is given
    rho      : optional explicit input ket/dm (dimension must equal N_basis)
    """
    for st in chain:
        if st not in VALID_STAGES:
            raise ValueError(f"Unknown stage {st!r}; valid: {VALID_STAGES}")

    if rho is not None:
        if rho.shape[0] != N_basis:
            raise ValueError(
                f"rho dimension {rho.shape[0]} != N_basis {N_basis}")
        out = rho
    else:
        out = make_state(state, nbar, N_basis, squeeze_angle=squeeze_angle,
                         sqz_fraction=sqz_fraction, parity=parity)

    for st in chain:
        if st == "sig":
            U = (-1j * s * signal_generator(N_basis, theta_sig)).expm()
            out = _apply_unitary(out, U)
        elif st == "ba":
            if chi_ba != 0.0:
                U = (-1j * ba_generator(chi_ba, N_basis, ba_type, theta_ba)).expm()
                out = _apply_unitary(out, U)
        elif st == "basig":
            G = s * signal_generator(N_basis, theta_sig)
            if chi_ba != 0.0:
                G = G + ba_generator(chi_ba, N_basis, ba_type, theta_ba)
            out = _apply_unitary(out, (-1j * G).expm())
        elif st == "loss_in":
            out = _loss_channel(out, eta_in, N_basis)
        elif st == "loss_out":
            out = _loss_channel(out, eta_out, N_basis)
        elif st == "pn":
            out = _dephasing_channel(out, pn, N_basis)

    return out


# ---------------------------------------------------------------------------
# Fock-cutoff convergence
# ---------------------------------------------------------------------------

def calculate_qfi_converged(dynamics=get_state_backaction, *, param_value=0.0,
                            param_type="s", N_start=30, N_max=400,
                            growth=1.5, rtol=1e-4, **kwargs):
    """
    Compute QFI with an automated Fock-cutoff convergence check: grow N_basis
    geometrically until successive QFI values agree to rtol.

    Returns (qfi, N_used, history) with history = [(N_basis, qfi), ...].
    The dynamics callable must accept N_basis and build its input state at
    that dimension (do not pass a fixed rho).
    """
    history = []
    N = int(N_start)
    q_prev = calculate_qfi(dynamics, param_value=param_value,
                           param_type=param_type, N_basis=N, **kwargs)
    history.append((N, q_prev))
    while True:
        N_next = max(N + 5, int(np.ceil(N * growth)))
        if N_next > N_max:
            raise RuntimeError(
                f"QFI not converged to rtol={rtol} by N_basis={N}: "
                f"history={history}")
        q_next = calculate_qfi(dynamics, param_value=param_value,
                               param_type=param_type, N_basis=N_next, **kwargs)
        history.append((N_next, q_next))
        scale = max(abs(q_next), 1e-30)
        if abs(q_next - q_prev) / scale < rtol:
            return q_next, N_next, history
        N, q_prev = N_next, q_next
